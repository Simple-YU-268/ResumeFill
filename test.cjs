const assert=require('node:assert/strict'),fs=require('node:fs');
const M=require('./matcher.js'),A=require('./adapters.js');
const sample=JSON.parse(fs.readFileSync(__dirname+'/sample.json','utf8'));
const values=M.flatten({...sample,education:[{school:'学校 A',major:'专业 A'},{school:'学校 B',major:'专业 B'}]});
const match=(label,extra={})=>M.match({tokens:[label],context:'',...extra},values)?.path;
assert.equal(match('姓名'),'basics.name');assert.equal(match('E-mail'),'basics.email');assert.equal(match('请输入手机号码'),'basics.phone');
assert.equal(match('学校',{section:'education'}),undefined);
assert.equal(match('学校',{section:'education',recordIndex:1}),'education.1.school');
assert.equal(match('专业',{section:'education',recordIndex:0}),'education.0.major');
assert.equal(match('验证码'),undefined);
assert.equal(M.match({label:'性别',tokens:[],context:''},{'basics.gender':''}).path,'basics.gender');
assert.equal(M.match({label:'性别',tokens:[],context:''},{gender:'女'}).path,'gender');
assert.equal(M.infer({label:'姓名'}).path,'basics.name');assert.equal(M.infer({label:'身份证号码'}).path,'basics.idNumber');assert.equal(M.infer({label:'父亲姓名'}),null);
assert.equal(M.match({label:'现居住地址',tokens:['city']},{'basics.city':'南京'}),null);
assert.equal(M.match({label:'city-field_anld7OmP',tokens:['city']},{'basics.city':'南京'}),null);
assert.equal(M.match({label:'父亲姓名',tokens:['name']},{'basics.name':'本人'}),null);
assert.equal(M.infer({label:'户籍所在地 · 市',regionRole:'hukou',regionLevel:'city'}).path,'basics.hukou.city');
assert.equal(M.match({tokens:['期望薪资'],context:''},M.flatten({custom:{期望薪资:'10000'}})).path,'custom.期望薪资');
const adapters=JSON.parse(fs.readFileSync(__dirname+'/sample-adapters.json','utf8'));A.validate(adapters);
assert.equal(A.choose(adapters,'http://127.0.0.1:8888/demo-advanced.html').id,'local-advanced-demo');
assert.equal(A.choose(adapters,'http://127.0.0.1:8888/other'),null);
assert.equal(A.choose(adapters,'https://127.0.0.1.evil.test/demo-advanced.html'),null);
assert.throws(()=>A.choose({adapters:[...adapters.adapters,...adapters.adapters]},'http://localhost/demo-advanced.html'),/多份/);
assert.throws(()=>A.validate({version:1,adapters:[{...adapters.adapters[0],hostnames:['*']}] }),/明确域名/);
assert.throws(()=>A.validate({version:1,adapters:[{...adapters.adapters[0],sections:[{key:'education',selector:'#e',fields:[{selector:'input',path:'education.0.school'}]}]}]}),/\*/);
assert.equal(A.recordPath('education.*.school',2),'education.2.school');
const f=[{label:'学校',section:'education',recordIndex:0,type:'input',options:null}];
assert.notEqual(A.fingerprint(f),A.fingerprint([{...f[0],recordIndex:1}]));
assert.notEqual(A.fingerprint(f),A.fingerprint([{...f[0],type:'select',options:['A','B']}]));
console.log('PASS: field aliases, repeated-record disambiguation, domain/path isolation, schema validation, form signatures');
