const assert=require('node:assert/strict'),C=require('./courier.js');
const now=Date.UTC(2026,10,11);
const job={id:'synthetic-job',companyKey:'synthetic-company',origin:'https://jobs.example.test'};
let state=C.enqueue([],job,now);
assert.equal(state[0].status,'queued');
assert.throws(()=>C.enqueue(state,job,now));
state=C.transition(state,job.id,'running',{},now+1);
assert.throws(()=>C.transition(state,job.id,'submitted',{},now+2));
state=C.transition(state,job.id,'handoff',{verified:3,value:'private',label:'private'},now+2);
assert.ok(!JSON.stringify(state).includes('private'));
state=C.transition(state,job.id,'submitted',{confirmedByUser:true},now+3);
assert.throws(()=>C.enqueue(state,{...job,id:'another'},now+4));
assert.equal(C.enqueue(state,{...job,id:'another',companyKey:'different'},now+1800004).length,2);
assert.throws(()=>C.enqueue([], {...job,origin:'https://jobs.example.test/private?secret=x'},now));
const receipts=Array.from({length:20},(_,i)=>({id:'job-'+i,companyKey:'company-'+i,origin:'https://other.example.test',at:now,updatedAt:now,status:'submitted'}));
assert.throws(()=>C.enqueue(receipts,job,now+1),/Daily/);
assert.throws(()=>C.enqueue([{...job,at:now,updatedAt:now,status:'skipped'}],{...job,id:'next'},now+1),/cooldown/);
const failures=Array.from({length:3},(_,i)=>({...job,id:'fail-'+i,companyKey:'fail-company-'+i,at:now-i,updatedAt:now-i,status:'failed'}));
assert.throws(()=>C.enqueue(failures,{...job,id:'next',companyKey:'next'},now+1800001),/circuit/);
let interrupted=C.transition(C.enqueue([],job,now),job.id,'running',{},now+1);
interrupted=C.recover(interrupted,job.id,now+2);
assert.equal(interrupted[0].status,'blocked');
assert.equal(interrupted[0].reason,'interrupted');
assert.throws(()=>C.recover(interrupted,job.id,now+3));
assert.equal(C.transition(interrupted,job.id,'queued',{},now+3)[0].status,'queued');
const exported=C.receipts([{...interrupted[0],label:'private',value:'private',url:'https://example.test/?private'}]);
assert.ok(!JSON.stringify(exported).includes('private'));
assert.equal(exported.version,1);
assert.equal(exported.applications[0].status,'blocked');
assert.deepEqual(C.validateReceipts(exported),exported);
assert.throws(()=>C.validateReceipts({version:1,applications:[{...exported.applications[0],origin:'https://jobs.example.test/?private'}]}));
assert.throws(()=>C.validateReceipts({version:1,applications:[{...exported.applications[0],status:'invented'}]}));
assert.throws(()=>C.validateReceipts({version:1,applications:[{...exported.applications[0],verified:-1}]}));
assert.throws(()=>C.validateReceipts({version:1,applications:[exported.applications[0],exported.applications[0]]}));
assert.ok(!JSON.stringify(C.validateReceipts({version:1,applications:[{...exported.applications[0],value:'private'}]})).includes('private'));
assert.equal(C.validateReceipts({...exported,revision:3}).revision,3);
assert.throws(()=>C.validateReceipts({...exported,revision:-1}));
console.log('PASS: queue transitions, human submission confirmation, duplicate/company quota and private payload omission');
